-- ---------------------------------------------------------
-- 5. Unified user-facing entitlement status
-- User sees percentages/status, never API cost.
-- ---------------------------------------------------------
create or replace function public.get_hwarang_ai_entitlement_status(p_user_id uuid)
returns table(
    training_allocation_credits bigint,
    training_balance_credits bigint,
    training_reserved_credits bigint,
    training_available_credits bigint,
    training_remaining_percent numeric,

    voice_allocation_seconds bigint,
    voice_balance_seconds bigint,
    voice_reserved_seconds bigint,
    voice_available_seconds bigint,
    voice_remaining_percent numeric,

    service_enabled boolean,
    text_enabled boolean,
    voice_enabled boolean,
    assessment_enabled boolean,
    soft_limit_percent integer,
    contact_label text,
    contact_url text
)
language sql
stable
security definer
set search_path = ''
as $$
    select
        tc.allocation_credits,
        tc.balance_credits,
        tc.reserved_credits,
        greatest(0::bigint, tc.balance_credits - tc.reserved_credits),
        case
            when tc.allocation_credits <= 0 then 0::numeric
            else round(
                greatest(
                    0::numeric,
                    (tc.balance_credits - tc.reserved_credits)::numeric
                    / tc.allocation_credits::numeric * 100
                ),
                1
            )
        end,

        va.allocation_seconds,
        va.balance_seconds,
        va.reserved_seconds,
        greatest(0::bigint, va.balance_seconds - va.reserved_seconds),
        case
            when va.allocation_seconds <= 0 then 0::numeric
            else round(
                greatest(
                    0::numeric,
                    (va.balance_seconds - va.reserved_seconds)::numeric
                    / va.allocation_seconds::numeric * 100
                ),
                1
            )
        end,

        cfg.service_enabled,
        cfg.text_enabled,
        cfg.voice_enabled,
        cfg.assessment_enabled,
        cfg.soft_limit_percent,
        cfg.contact_label,
        cfg.contact_url
    from public.hwarang_ai_credit_accounts tc
    join public.hwarang_voice_accounts va
      on va.user_id = tc.user_id
    cross join public.hwarang_ai_runtime_config cfg
    where tc.user_id = p_user_id
      and cfg.config_id = 1;
$$;

-- ---------------------------------------------------------
-- 6. Super-admin VOICE allowance adjustment
-- Amount is supplied in whole minutes to keep admin UI simple.
-- ---------------------------------------------------------
create or replace function public.admin_adjust_hwarang_voice_minutes(
    p_actor_user_id uuid,
    p_target_user_id uuid,
    p_operation text,
    p_minutes bigint,
    p_note text default null
)
returns table(
    allocation_seconds bigint,
    balance_seconds bigint,
    reserved_seconds bigint
)
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_account public.hwarang_voice_accounts%rowtype;
    v_seconds bigint;
    v_delta bigint;
begin
    if not exists (
        select 1
        from public.profiles
        where id = p_actor_user_id
          and role = 'super_admin'
          and is_active = true
    ) then
        raise exception 'SUPER_ADMIN_REQUIRED';
    end if;

    if p_operation not in ('grant','revoke','reset') then
        raise exception 'INVALID_VOICE_OPERATION';
    end if;

    if p_minutes < 0 then
        raise exception 'INVALID_VOICE_MINUTES';
    end if;

    v_seconds := p_minutes * 60;

    insert into public.hwarang_voice_accounts(user_id)
    values (p_target_user_id)
    on conflict (user_id) do nothing;

    select *
    into v_account
    from public.hwarang_voice_accounts
    where user_id = p_target_user_id
    for update;

    if v_account.reserved_seconds > 0 and p_operation in ('revoke','reset') then
        raise exception 'VOICE_ACTIVE_RESERVATION';
    end if;

    if p_operation = 'grant' then
        v_delta := v_seconds;

        update public.hwarang_voice_accounts
        set allocation_seconds = allocation_seconds + v_seconds,
            balance_seconds = balance_seconds + v_seconds,
            updated_at = now()
        where user_id = p_target_user_id
        returning * into v_account;

    elsif p_operation = 'revoke' then
        if v_seconds > v_account.balance_seconds then
            raise exception 'VOICE_REVOKE_EXCEEDS_BALANCE';
        end if;

        v_delta := -v_seconds;

        update public.hwarang_voice_accounts
        set allocation_seconds = greatest(0, allocation_seconds - v_seconds),
            balance_seconds = balance_seconds - v_seconds,
            updated_at = now()
        where user_id = p_target_user_id
        returning * into v_account;

    else
        v_delta := v_seconds - v_account.balance_seconds;

        update public.hwarang_voice_accounts
        set allocation_seconds = v_seconds,
            balance_seconds = v_seconds,
            reserved_seconds = 0,
            updated_at = now()
        where user_id = p_target_user_id
        returning * into v_account;
    end if;

    insert into public.hwarang_voice_ledger(
        user_id,
        entry_type,
        delta_seconds,
        balance_after_seconds,
        allocation_after_seconds,
        actor_user_id,
        note
    )
    values (
        p_target_user_id,
        p_operation,
        v_delta,
        v_account.balance_seconds,
        v_account.allocation_seconds,
        p_actor_user_id,
        nullif(btrim(coalesce(p_note,'')), '')
    );

    insert into public.hwarang_admin_audit_log(
        actor_user_id,
        target_user_id,
        action,
        details
    )
    values (
        p_actor_user_id,
        p_target_user_id,
        'voice_minutes_' || p_operation,
        jsonb_build_object(
            'minutes', p_minutes,
            'delta_seconds', v_delta,
            'balance_after_seconds', v_account.balance_seconds,
            'allocation_after_seconds', v_account.allocation_seconds,
            'note', p_note
        )
    );

    return query
    select
        v_account.allocation_seconds,
        v_account.balance_seconds,
        v_account.reserved_seconds;
end;
$$;

