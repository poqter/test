        raise exception 'AI_SESSION_LOCK_NOT_FOUND';
    end if;
end;
$$;

-- ---------------------------------------------------------
-- 7. Replace reservation pruning so both billing buckets recover safely.
-- ---------------------------------------------------------
create or replace function private.prune_hwarang_ai_reservations()
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
    r record;
begin
    for r in
        select
            request_id,
            user_id,
            billing_bucket,
            reserved_credits,
            reserved_voice_seconds
        from public.hwarang_ai_request_registry
        where status in ('reserved','processing')
          and expires_at < now()
        for update skip locked
    loop
        if r.billing_bucket = 'VOICE' then
            update public.hwarang_voice_accounts
            set reserved_seconds = greatest(0, reserved_seconds - r.reserved_voice_seconds),
                updated_at = now()
            where user_id = r.user_id;
        else
            update public.hwarang_ai_credit_accounts
            set reserved_credits = greatest(0, reserved_credits - r.reserved_credits),
                updated_at = now()
            where user_id = r.user_id;
        end if;

        update public.hwarang_ai_request_registry
        set status = 'expired',
            completed_at = now()
        where request_id = r.request_id;
    end loop;
end;
$$;

revoke all on function private.prune_hwarang_ai_reservations() from public;

-- ---------------------------------------------------------
-- 8. TEXT / COACH / EVALUATOR reservation remains Training Credit only.
-- VOICE must use the separate voice-time reservation function below.
-- ---------------------------------------------------------
create or replace function public.reserve_hwarang_ai_request(
    p_user_id uuid,
    p_academy_session_id uuid,
    p_turn_no integer,
    p_purpose text,
    p_interaction_mode text,
    p_idempotency_key text,
    p_estimated_credits bigint
)
returns table(
    request_id uuid,
    request_status text,
    duplicate boolean,
    available_credits bigint
)
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_config public.hwarang_ai_runtime_config%rowtype;
    v_account public.hwarang_ai_credit_accounts%rowtype;
    v_request public.hwarang_ai_request_registry%rowtype;
    v_permissions text[];
begin
    perform private.prune_hwarang_ai_reservations();

    if p_purpose not in ('CUSTOMER','COACH','EVALUATOR') then
        if p_purpose = 'VOICE' then
            raise exception 'VOICE_USE_SEPARATE_ALLOWANCE';
        end if;
        raise exception 'INVALID_AI_PURPOSE';
    end if;

    if p_interaction_mode <> 'TEXT' then
        raise exception 'TEXT_RESERVATION_REQUIRES_TEXT_MODE';
    end if;

    if p_estimated_credits <= 0 then
        raise exception 'INVALID_CREDIT_ESTIMATE';
    end if;

    if p_idempotency_key is null
       or btrim(p_idempotency_key) = ''
       or char_length(p_idempotency_key) > 180 then
        raise exception 'INVALID_IDEMPOTENCY_KEY';
    end if;

    select *
    into v_request
    from public.hwarang_ai_request_registry
    where idempotency_key = p_idempotency_key;

    if found then
        if v_request.user_id <> p_user_id then
            raise exception 'IDEMPOTENCY_KEY_CONFLICT';
        end if;

        select greatest(0, balance_credits - reserved_credits)
        into available_credits
        from public.hwarang_ai_credit_accounts
        where user_id = p_user_id;

        request_id := v_request.request_id;
        request_status := v_request.status;
        duplicate := true;
        return next;
        return;
    end if;

    if not exists (
        select 1
        from public.profiles
        where id = p_user_id
          and is_active = true
    ) then
        raise exception 'INACTIVE_USER';
    end if;

    select *
    into v_config
    from public.hwarang_ai_runtime_config
    where config_id = 1;

    if not v_config.service_enabled then
        raise exception 'AI_SERVICE_DISABLED';
    end if;

    if not v_config.text_enabled then
        raise exception 'AI_TEXT_DISABLED';
    end if;

    if p_purpose = 'EVALUATOR' and not v_config.assessment_enabled then
        raise exception 'AI_ASSESSMENT_DISABLED';
    end if;

    select array_agg(permission_code)
    into v_permissions
    from public.get_hwarang_effective_permissions(p_user_id);

    if not ('academy.simulator' = any(coalesce(v_permissions,array[]::text[]))) then
        raise exception 'AI_SIMULATOR_PERMISSION_REQUIRED';
    end if;

    if p_purpose = 'EVALUATOR'
       and not ('academy.formal_ai_assessment' = any(coalesce(v_permissions,array[]::text[]))) then
        raise exception 'AI_ASSESSMENT_PERMISSION_REQUIRED';
    end if;

    insert into public.hwarang_ai_credit_accounts(user_id)
    values (p_user_id)
    on conflict (user_id) do nothing;

    select *
    into v_account
    from public.hwarang_ai_credit_accounts
    where user_id = p_user_id
    for update;

    if (v_account.balance_credits - v_account.reserved_credits) < p_estimated_credits then
        insert into public.hwarang_activity_log(
            user_id, app_code, event_code, feature_code, outcome, metadata
        )
        values (
            p_user_id,
            'academy',
            'AI_REQUEST_BLOCKED',
            'academy.simulator',
            'blocked',
            jsonb_build_object('reason','training_credit_exhausted','purpose',p_purpose)
        );

        raise exception 'AI_CREDIT_EXHAUSTED';
    end if;

    insert into public.hwarang_ai_request_registry(
        idempotency_key,
        user_id,
        academy_session_id,
        turn_no,
        purpose,
        interaction_mode,
        billing_bucket,
        status,
        reserved_credits,
        reserved_voice_seconds
    )
    values (
        btrim(p_idempotency_key),
        p_user_id,
        p_academy_session_id,
        p_turn_no,
        p_purpose,
        'TEXT',
        'TRAINING',
        'reserved',
        p_estimated_credits,
        0
    )
    returning * into v_request;

    update public.hwarang_ai_credit_accounts
    set reserved_credits = reserved_credits + p_estimated_credits,
        updated_at = now()
    where user_id = p_user_id
    returning * into v_account;

    request_id := v_request.request_id;
    request_status := v_request.status;
    duplicate := false;
    available_credits := greatest(
        0,
        v_account.balance_credits - v_account.reserved_credits
    );

    return next;
end;
$$;

-- ---------------------------------------------------------
-- 9. VOICE reservation.
-- The caller requests a session budget; DB returns the allowed number of seconds.
-- The platform hard cap defaults to 30 minutes, which is above normal DEEP usage.
-- ---------------------------------------------------------
create or replace function public.reserve_hwarang_voice_request(
    p_user_id uuid,
    p_academy_session_id uuid,
    p_turn_no integer,
    p_idempotency_key text,
    p_requested_seconds bigint
)
returns table(
    request_id uuid,
    request_status text,
    duplicate boolean,
    allowed_voice_seconds bigint,
    available_voice_seconds bigint
)
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_config public.hwarang_ai_runtime_config%rowtype;
    v_account public.hwarang_voice_accounts%rowtype;
    v_request public.hwarang_ai_request_registry%rowtype;
    v_permissions text[];
    v_hard_minutes numeric;
    v_hard_seconds bigint;
    v_allowed bigint;
begin
    perform private.prune_hwarang_ai_reservations();

    if p_requested_seconds <= 0 then
        raise exception 'INVALID_VOICE_SECONDS';
    end if;

    if p_idempotency_key is null
       or btrim(p_idempotency_key) = ''
       or char_length(p_idempotency_key) > 180 then
        raise exception 'INVALID_IDEMPOTENCY_KEY';
    end if;

    select *
    into v_request
    from public.hwarang_ai_request_registry
    where idempotency_key = p_idempotency_key;

    if found then
        if v_request.user_id <> p_user_id then
            raise exception 'IDEMPOTENCY_KEY_CONFLICT';
        end if;

        select greatest(0, balance_seconds - reserved_seconds)
        into available_voice_seconds
        from public.hwarang_voice_accounts
        where user_id = p_user_id;

        request_id := v_request.request_id;
        request_status := v_request.status;
        duplicate := true;
        allowed_voice_seconds := v_request.reserved_voice_seconds;
        return next;
        return;
    end if;

    if not exists (
        select 1
        from public.profiles
        where id = p_user_id
          and is_active = true
    ) then
        raise exception 'INACTIVE_USER';
    end if;

    select *
    into v_config
    from public.hwarang_ai_runtime_config
    where config_id = 1;

    if not v_config.service_enabled then
        raise exception 'AI_SERVICE_DISABLED';
    end if;

    if not v_config.voice_enabled then
        raise exception 'AI_VOICE_DISABLED';
    end if;

    select array_agg(permission_code)
    into v_permissions
    from public.get_hwarang_effective_permissions(p_user_id);

    if not ('academy.simulator' = any(coalesce(v_permissions,array[]::text[]))) then
        raise exception 'AI_SIMULATOR_PERMISSION_REQUIRED';
    end if;

    if not ('academy.voice_simulator' = any(coalesce(v_permissions,array[]::text[]))) then
        raise exception 'AI_VOICE_PERMISSION_REQUIRED';
    end if;

    insert into public.hwarang_voice_accounts(user_id)
    values (p_user_id)
    on conflict (user_id) do nothing;

    select *
    into v_account
    from public.hwarang_voice_accounts
    where user_id = p_user_id
    for update;

    select hard_limit
    into v_hard_minutes
    from public.hwarang_ai_limit_policies
    where scope_type = 'app'
      and scope_key = 'academy.voice'
      and metric = 'voice_minutes'
      and is_enabled = true
    limit 1;

    v_hard_seconds := greatest(
        60::bigint,
        floor(coalesce(v_hard_minutes,30) * 60)::bigint
    );

    v_allowed := least(
        p_requested_seconds,
        v_hard_seconds,
        greatest(0::bigint, v_account.balance_seconds - v_account.reserved_seconds)
    );

    if v_allowed <= 0 then
        insert into public.hwarang_activity_log(
            user_id, app_code, event_code, feature_code, outcome, metadata
        )
        values (
            p_user_id,
            'academy',
            'AI_REQUEST_BLOCKED',
            'academy.voice_simulator',
            'blocked',
            jsonb_build_object('reason','voice_allowance_exhausted')
        );

        raise exception 'VOICE_ALLOWANCE_EXHAUSTED';
    end if;

    insert into public.hwarang_ai_request_registry(
        idempotency_key,
        user_id,
        academy_session_id,
        turn_no,
        purpose,
        interaction_mode,
        billing_bucket,
        status,
        reserved_credits,
        reserved_voice_seconds
    )
    values (
        btrim(p_idempotency_key),
        p_user_id,
        p_academy_session_id,
        p_turn_no,
        'VOICE',
        'VOICE',
        'VOICE',
        'reserved',
        0,
        v_allowed
    )
    returning * into v_request;

    update public.hwarang_voice_accounts
    set reserved_seconds = reserved_seconds + v_allowed,
        updated_at = now()
    where user_id = p_user_id
    returning * into v_account;

    request_id := v_request.request_id;
    request_status := v_request.status;
    duplicate := false;
    allowed_voice_seconds := v_allowed;
    available_voice_seconds := greatest(
        0,
        v_account.balance_seconds - v_account.reserved_seconds
    );

    return next;
end;
$$;

-- ---------------------------------------------------------
-- 10. Finalize VOICE usage and return unused reserved seconds.
-- ---------------------------------------------------------
create or replace function public.finalize_hwarang_voice_request(
    p_request_id uuid,
    p_result_status text,
    p_actual_seconds bigint
)
returns table(
    balance_seconds bigint,
    reserved_seconds bigint,
    available_seconds bigint
)
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_request public.hwarang_ai_request_registry%rowtype;
    v_account public.hwarang_voice_accounts%rowtype;
    v_other_reserved bigint;
begin
    if p_result_status not in ('completed','failed') then
        raise exception 'INVALID_AI_RESULT_STATUS';
    end if;

    if p_actual_seconds < 0 then
        raise exception 'INVALID_VOICE_SECONDS';
    end if;

    select *
    into v_request
    from public.hwarang_ai_request_registry
    where request_id = p_request_id
    for update;

    if not found then
        raise exception 'AI_REQUEST_NOT_FOUND';
    end if;

    if v_request.billing_bucket <> 'VOICE' then
        raise exception 'AI_REQUEST_NOT_VOICE';
    end if;

    if v_request.status in ('completed','failed','expired') then
        select
            a.balance_seconds,
            a.reserved_seconds,
            greatest(0, a.balance_seconds - a.reserved_seconds)
        into balance_seconds, reserved_seconds, available_seconds
        from public.hwarang_voice_accounts a
        where a.user_id = v_request.user_id;

        return next;
        return;
    end if;

    if p_actual_seconds > v_request.reserved_voice_seconds then
        raise exception 'VOICE_USAGE_EXCEEDS_RESERVATION';
    end if;

    select *
    into v_account
    from public.hwarang_voice_accounts
    where user_id = v_request.user_id
    for update;

    v_other_reserved := greatest(
        0,
        v_account.reserved_seconds - v_request.reserved_voice_seconds
    );

    if p_result_status = 'completed' then
        update public.hwarang_voice_accounts
        set balance_seconds = balance_seconds - p_actual_seconds,
            reserved_seconds = v_other_reserved,
            updated_at = now()
        where user_id = v_request.user_id
        returning * into v_account;

        if p_actual_seconds > 0 then
            insert into public.hwarang_voice_ledger(
                user_id,
                entry_type,
                delta_seconds,
                balance_after_seconds,
                allocation_after_seconds,
                request_id,
                note
            )
            values (
                v_request.user_id,
                'consume',
                -p_actual_seconds,
                v_account.balance_seconds,
                v_account.allocation_seconds,
                v_request.request_id,
                'Voice training usage'
            );
        end if;

        update public.hwarang_ai_request_registry
        set status = 'completed',
            actual_voice_seconds = p_actual_seconds,
            completed_at = now()
        where request_id = p_request_id;

    else
        update public.hwarang_voice_accounts
        set reserved_seconds = v_other_reserved,
            updated_at = now()
        where user_id = v_request.user_id
        returning * into v_account;

        update public.hwarang_ai_request_registry
        set status = 'failed',
            actual_voice_seconds = 0,
            completed_at = now()
        where request_id = p_request_id;
    end if;

    balance_seconds := v_account.balance_seconds;
    reserved_seconds := v_account.reserved_seconds;
    available_seconds := greatest(
        0,
        v_account.balance_seconds - v_account.reserved_seconds
    );

    return next;
end;
$$;

-- ---------------------------------------------------------
-- 11. Super-admin-only model policy update.
-- Text provider model IDs are filled only at API connection time.
-- ---------------------------------------------------------
create or replace function public.admin_update_hwarang_ai_model_policy(
    p_actor_user_id uuid,
    p_role_code text,
    p_provider_model text,
    p_max_output_tokens integer
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
    if not exists (
        select 1
        from public.profiles
        where id = p_actor_user_id
          and role = 'super_admin'
          and is_active = true
    ) then
        raise exception 'SUPER_ADMIN_REQUIRED';
    end if;

    if p_role_code not in ('CUSTOMER','COACH','EVALUATOR','VOICE') then
        raise exception 'INVALID_AI_ROLE';
    end if;

    if p_max_output_tokens is not null and p_max_output_tokens <= 0 then
        raise exception 'INVALID_OUTPUT_TOKEN_LIMIT';
    end if;

    update public.hwarang_ai_model_policy
    set provider_model = nullif(btrim(coalesce(p_provider_model,'')), ''),
        max_output_tokens = p_max_output_tokens,
        updated_by = p_actor_user_id,
        updated_at = now()
    where role_code = p_role_code;

    if not found then
        raise exception 'AI_ROLE_NOT_FOUND';
    end if;

    insert into public.hwarang_admin_audit_log(
        actor_user_id,
        action,
        details
    )
    values (
        p_actor_user_id,
        'ai_model_policy_updated',
        jsonb_build_object(
            'role_code', p_role_code,
            'provider_model', nullif(btrim(coalesce(p_provider_model,'')), ''),
            'max_output_tokens', p_max_output_tokens
        )
    );
end;
$$;

-- ---------------------------------------------------------
-- 12. Admin operations view: append VOICE allowance columns.
-- Existing column order is preserved; new columns are appended.
-- ---------------------------------------------------------
create or replace view public.hwarang_admin_user_operations_view
with (security_invoker = true)
as
select
    p.*,
    recent_session.last_seen_at as recent_seen_at,
    recent_session.status as recent_session_status,
    recent_activity.event_code as recent_activity_code,
    recent_activity.feature_code as recent_feature_code,
    recent_activity.created_at as recent_activity_at,
    coalesce(ca.allocation_credits,0) as training_credit_allocation,
    coalesce(ca.balance_credits,0) as training_credit_balance,
    coalesce(ca.reserved_credits,0) as training_credit_reserved,
    coalesce(va.allocation_seconds,0) as voice_allocation_seconds,
    coalesce(va.balance_seconds,0) as voice_balance_seconds,
    coalesce(va.reserved_seconds,0) as voice_reserved_seconds
from public.profiles_admin_view p
left join lateral (
    select s.last_seen_at, s.status
    from public.hwarang_user_sessions s
    where s.user_id = p.user_id
    order by s.last_seen_at desc
    limit 1
) recent_session on true
left join lateral (
    select a.event_code, a.feature_code, a.created_at
    from public.hwarang_activity_log a
    where a.user_id = p.user_id
    order by a.created_at desc
    limit 1
) recent_activity on true
left join public.hwarang_ai_credit_accounts ca
    on ca.user_id = p.user_id
left join public.hwarang_voice_accounts va
    on va.user_id = p.user_id;

