-- 6B. Active AI-session heartbeat.
-- Voice and long text sessions refresh this periodically; no click-level logging.
-- ---------------------------------------------------------
create or replace function public.heartbeat_hwarang_ai_session(
    p_user_id uuid,
    p_academy_session_id uuid
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
    update public.hwarang_ai_session_locks
    set last_seen_at = now(),
        expires_at = now() + interval '20 minutes'
    where user_id = p_user_id
