create table if not exists public.hwarang_voice_accounts (
    user_id uuid primary key references public.profiles(id) on delete cascade,
    allocation_seconds bigint not null default 0 check (allocation_seconds >= 0),
    balance_seconds bigint not null default 0 check (balance_seconds >= 0),
    reserved_seconds bigint not null default 0 check (reserved_seconds >= 0),
    updated_at timestamptz not null default now(),
    check (reserved_seconds <= balance_seconds)
);

insert into public.hwarang_voice_accounts(user_id)
select id from public.profiles
on conflict (user_id) do nothing;

create table if not exists public.hwarang_voice_ledger (
    id bigint generated by default as identity primary key,
    user_id uuid not null references public.profiles(id) on delete cascade,
    entry_type text not null
        check (entry_type in ('grant','revoke','consume','refund','reset','adjust')),
    delta_seconds bigint not null,
    balance_after_seconds bigint not null check (balance_after_seconds >= 0),
    allocation_after_seconds bigint not null check (allocation_after_seconds >= 0),
    request_id uuid references public.hwarang_ai_request_registry(request_id) on delete set null,
    actor_user_id uuid references public.profiles(id) on delete set null,
    note text,
    created_at timestamptz not null default now()
);

create index if not exists hwarang_voice_ledger_user_created_idx
on public.hwarang_voice_ledger(user_id, created_at desc);

-- Existing request/usage tables are extended rather than replaced.
alter table public.hwarang_ai_request_registry
    add column if not exists billing_bucket text not null default 'TRAINING',
    add column if not exists reserved_voice_seconds bigint not null default 0,
    add column if not exists actual_voice_seconds bigint not null default 0;

do $$
begin
    if not exists (
        select 1
        from pg_constraint
        where conname = 'hwarang_ai_request_billing_bucket_check'
          and conrelid = 'public.hwarang_ai_request_registry'::regclass
    ) then
        alter table public.hwarang_ai_request_registry
            add constraint hwarang_ai_request_billing_bucket_check
            check (billing_bucket in ('TRAINING','VOICE'));
    end if;

    if not exists (
        select 1
        from pg_constraint
        where conname = 'hwarang_ai_request_reserved_voice_nonnegative'
          and conrelid = 'public.hwarang_ai_request_registry'::regclass
    ) then
        alter table public.hwarang_ai_request_registry
            add constraint hwarang_ai_request_reserved_voice_nonnegative
            check (reserved_voice_seconds >= 0);
    end if;

    if not exists (
        select 1
        from pg_constraint
        where conname = 'hwarang_ai_request_actual_voice_nonnegative'
          and conrelid = 'public.hwarang_ai_request_registry'::regclass
    ) then
        alter table public.hwarang_ai_request_registry
            add constraint hwarang_ai_request_actual_voice_nonnegative
            check (actual_voice_seconds >= 0);
    end if;
end
$$;

