-- 13) Super-admin Training Credit adjustment
create or replace function public.admin_adjust_hwarang_ai_credits(
    p_actor_user_id uuid,
    p_target_user_id uuid,
    p_operation text,
    p_amount bigint,
    p_note text default null
)
returns table(allocation_credits bigint,balance_credits bigint,reserved_credits bigint)
language plpgsql
security definer
set search_path=''
as $$
declare
    v_account public.hwarang_ai_credit_accounts%rowtype;
    v_delta bigint;
begin
    if not exists (
        select 1 from public.profiles
        where id=p_actor_user_id and role='super_admin' and is_active=true
    ) then raise exception 'SUPER_ADMIN_REQUIRED'; end if;

    if p_operation not in ('grant','revoke','reset') then
        raise exception 'INVALID_CREDIT_OPERATION';
    end if;
    if p_amount<0 then raise exception 'INVALID_CREDIT_AMOUNT'; end if;

    insert into public.hwarang_ai_credit_accounts(user_id)
    values (p_target_user_id)
    on conflict (user_id) do nothing;

    select * into v_account
    from public.hwarang_ai_credit_accounts
    where user_id=p_target_user_id
    for update;

    if v_account.reserved_credits>0 and p_operation in ('revoke','reset') then
        raise exception 'AI_ACTIVE_RESERVATION';
    end if;

    if p_operation='grant' then
        v_delta:=p_amount;
        update public.hwarang_ai_credit_accounts
        set allocation_credits=allocation_credits+p_amount,
            balance_credits=balance_credits+p_amount,
            updated_at=now()
        where user_id=p_target_user_id
        returning * into v_account;
    elsif p_operation='revoke' then
        if p_amount>v_account.balance_credits then
            raise exception 'AI_CREDIT_REVOKE_EXCEEDS_BALANCE';
        end if;
        v_delta:=-p_amount;
        update public.hwarang_ai_credit_accounts
        set allocation_credits=greatest(0,allocation_credits-p_amount),
            balance_credits=balance_credits-p_amount,
            updated_at=now()
        where user_id=p_target_user_id
        returning * into v_account;
    else
        v_delta:=p_amount-v_account.balance_credits;
        update public.hwarang_ai_credit_accounts
        set allocation_credits=p_amount,
            balance_credits=p_amount,
            reserved_credits=0,
            updated_at=now()
        where user_id=p_target_user_id
        returning * into v_account;
    end if;

    insert into public.hwarang_ai_credit_ledger(
        user_id,entry_type,delta_credits,balance_after,allocation_after,actor_user_id,note
    )
    values (
        p_target_user_id,p_operation,v_delta,v_account.balance_credits,
        v_account.allocation_credits,p_actor_user_id,
        nullif(btrim(coalesce(p_note,'')),'')
    );

    insert into public.hwarang_admin_audit_log(actor_user_id,target_user_id,action,details)
    values (
        p_actor_user_id,p_target_user_id,'ai_credit_'||p_operation,
        jsonb_build_object(
            'amount',p_amount,'delta',v_delta,
            'balance_after',v_account.balance_credits,
            'allocation_after',v_account.allocation_credits,
            'note',p_note
        )
    );

    return query
    select v_account.allocation_credits,v_account.balance_credits,v_account.reserved_credits;
end;
$$;

-- 14) One active AI session lock
create or replace function public.acquire_hwarang_ai_session(
    p_user_id uuid, p_academy_session_id uuid
)
returns void
language plpgsql
security definer
set search_path=''
as $$
declare v_existing public.hwarang_ai_session_locks%rowtype;
begin
    delete from public.hwarang_ai_session_locks where expires_at<now();

    select * into v_existing
    from public.hwarang_ai_session_locks
    where user_id=p_user_id
    for update;

    if found and v_existing.academy_session_id<>p_academy_session_id then
        raise exception 'AI_ACTIVE_SESSION_EXISTS';
    end if;

    insert into public.hwarang_ai_session_locks(
        user_id,academy_session_id,acquired_at,last_seen_at,expires_at
    )
    values (
        p_user_id,p_academy_session_id,now(),now(),now()+interval '20 minutes'
    )
    on conflict (user_id) do update
    set last_seen_at=now(),expires_at=now()+interval '20 minutes'
    where public.hwarang_ai_session_locks.academy_session_id=excluded.academy_session_id;
end;
$$;

