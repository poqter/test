-- 15) Reservation cleanup
create or replace function private.prune_hwarang_ai_reservations()
returns void
language plpgsql
security definer
set search_path=''
as $$
declare r record;
begin
    for r in
        select request_id,user_id,reserved_credits
        from public.hwarang_ai_request_registry
        where status in ('reserved','processing') and expires_at<now()
        for update skip locked
    loop
        update public.hwarang_ai_credit_accounts
        set reserved_credits=greatest(0,reserved_credits-r.reserved_credits),
            updated_at=now()
        where user_id=r.user_id;

        update public.hwarang_ai_request_registry
        set status='expired',completed_at=now()
        where request_id=r.request_id;
    end loop;
end;
$$;
revoke all on function private.prune_hwarang_ai_reservations() from public;

-- 16) Atomic reservation BEFORE external AI call
create or replace function public.reserve_hwarang_ai_request(
    p_user_id uuid,
    p_academy_session_id uuid,
    p_turn_no integer,
    p_purpose text,
    p_interaction_mode text,
    p_idempotency_key text,
    p_estimated_credits bigint
)
returns table(
    request_id uuid,
    request_status text,
    duplicate boolean,
    available_credits bigint
)
language plpgsql
security definer
set search_path=''
as $$
declare
    v_config public.hwarang_ai_runtime_config%rowtype;
    v_account public.hwarang_ai_credit_accounts%rowtype;
    v_request public.hwarang_ai_request_registry%rowtype;
    v_permissions text[];
begin
    perform private.prune_hwarang_ai_reservations();

    if p_purpose not in ('CUSTOMER','COACH','EVALUATOR','VOICE') then
        raise exception 'INVALID_AI_PURPOSE';
    end if;
    if p_interaction_mode not in ('TEXT','VOICE') then
        raise exception 'INVALID_INTERACTION_MODE';
    end if;
    if p_estimated_credits<=0 then raise exception 'INVALID_CREDIT_ESTIMATE'; end if;
    if p_idempotency_key is null or btrim(p_idempotency_key)='' or char_length(p_idempotency_key)>180 then
        raise exception 'INVALID_IDEMPOTENCY_KEY';
    end if;

    select * into v_request
    from public.hwarang_ai_request_registry
    where idempotency_key=p_idempotency_key;

    if found then
        if v_request.user_id<>p_user_id then raise exception 'IDEMPOTENCY_KEY_CONFLICT'; end if;
        select greatest(0,balance_credits-reserved_credits)
        into available_credits
        from public.hwarang_ai_credit_accounts
        where user_id=p_user_id;

        request_id:=v_request.request_id;
        request_status:=v_request.status;
        duplicate:=true;
        return next;
        return;
    end if;

    if not exists (
        select 1 from public.profiles where id=p_user_id and is_active=true
    ) then raise exception 'INACTIVE_USER'; end if;

    select * into v_config
    from public.hwarang_ai_runtime_config where config_id=1;

    if not v_config.service_enabled then raise exception 'AI_SERVICE_DISABLED'; end if;

    if p_interaction_mode='VOICE' then
        if not v_config.voice_enabled then raise exception 'AI_VOICE_DISABLED'; end if;
    else
        if not v_config.text_enabled then raise exception 'AI_TEXT_DISABLED'; end if;
    end if;

    if p_purpose='EVALUATOR' and not v_config.assessment_enabled then
        raise exception 'AI_ASSESSMENT_DISABLED';
    end if;

    select array_agg(permission_code) into v_permissions
    from public.get_hwarang_effective_permissions(p_user_id);

    if not ('academy.simulator'=any(coalesce(v_permissions,array[]::text[]))) then
        raise exception 'AI_SIMULATOR_PERMISSION_REQUIRED';
    end if;
    if p_interaction_mode='VOICE'
       and not ('academy.voice_simulator'=any(coalesce(v_permissions,array[]::text[]))) then
        raise exception 'AI_VOICE_PERMISSION_REQUIRED';
    end if;
    if p_purpose='EVALUATOR'
       and not ('academy.formal_ai_assessment'=any(coalesce(v_permissions,array[]::text[]))) then
        raise exception 'AI_ASSESSMENT_PERMISSION_REQUIRED';
    end if;

    insert into public.hwarang_ai_credit_accounts(user_id)
    values (p_user_id)
    on conflict (user_id) do nothing;

    select * into v_account
    from public.hwarang_ai_credit_accounts
    where user_id=p_user_id
    for update;

    if (v_account.balance_credits-v_account.reserved_credits)<p_estimated_credits then
        insert into public.hwarang_activity_log(
            user_id,app_code,event_code,feature_code,outcome,metadata
        ) values (
            p_user_id,'academy','AI_REQUEST_BLOCKED','academy.simulator','blocked',
            jsonb_build_object('reason','credit_exhausted','purpose',p_purpose)
        );
        raise exception 'AI_CREDIT_EXHAUSTED';
    end if;

    insert into public.hwarang_ai_request_registry(
        idempotency_key,user_id,academy_session_id,turn_no,purpose,
        interaction_mode,status,reserved_credits
    )
    values (
        btrim(p_idempotency_key),p_user_id,p_academy_session_id,p_turn_no,p_purpose,
        p_interaction_mode,'reserved',p_estimated_credits
    )
    returning * into v_request;

    update public.hwarang_ai_credit_accounts
    set reserved_credits=reserved_credits+p_estimated_credits,updated_at=now()
    where user_id=p_user_id
    returning * into v_account;

    request_id:=v_request.request_id;
    request_status:=v_request.status;
    duplicate:=false;
    available_credits:=greatest(0,v_account.balance_credits-v_account.reserved_credits);
    return next;
end;
$$;

-- 17) Finalize reservation after API result
create or replace function public.finalize_hwarang_ai_request(
    p_request_id uuid,
    p_result_status text,
    p_actual_credits bigint
)
returns table(balance_credits bigint,reserved_credits bigint,available_credits bigint)
language plpgsql
security definer
set search_path=''
as $$
declare
    v_request public.hwarang_ai_request_registry%rowtype;
    v_account public.hwarang_ai_credit_accounts%rowtype;
    v_other_reserved bigint;
begin
    if p_result_status not in ('completed','failed') then raise exception 'INVALID_AI_RESULT_STATUS'; end if;
    if p_actual_credits<0 then raise exception 'INVALID_CREDIT_AMOUNT'; end if;

    select * into v_request
    from public.hwarang_ai_request_registry
    where request_id=p_request_id
    for update;

    if not found then raise exception 'AI_REQUEST_NOT_FOUND'; end if;

    if v_request.status in ('completed','failed','expired') then
        select a.balance_credits,a.reserved_credits,
               greatest(0,a.balance_credits-a.reserved_credits)
        into balance_credits,reserved_credits,available_credits
        from public.hwarang_ai_credit_accounts a
        where a.user_id=v_request.user_id;
        return next;
        return;
    end if;

    select * into v_account
    from public.hwarang_ai_credit_accounts
    where user_id=v_request.user_id
    for update;

    if p_result_status='completed' then
        v_other_reserved:=greatest(0,v_account.reserved_credits-v_request.reserved_credits);

        if p_actual_credits>(v_account.balance_credits-v_other_reserved) then
            raise exception 'AI_CREDIT_RECONCILE_FAILED';
        end if;

        update public.hwarang_ai_credit_accounts
        set balance_credits=balance_credits-p_actual_credits,
            reserved_credits=v_other_reserved,
            updated_at=now()
        where user_id=v_request.user_id
        returning * into v_account;

        if p_actual_credits>0 then
            insert into public.hwarang_ai_credit_ledger(
                user_id,entry_type,delta_credits,balance_after,allocation_after,request_id,note
            ) values (
                v_request.user_id,'consume',-p_actual_credits,
                v_account.balance_credits,v_account.allocation_credits,
                v_request.request_id,'AI training usage'
            );
        end if;

        update public.hwarang_ai_request_registry
        set status='completed',actual_credits=p_actual_credits,completed_at=now()
        where request_id=p_request_id;
    else
        update public.hwarang_ai_credit_accounts
        set reserved_credits=greatest(0,reserved_credits-v_request.reserved_credits),
            updated_at=now()
        where user_id=v_request.user_id
        returning * into v_account;

        update public.hwarang_ai_request_registry
        set status='failed',actual_credits=0,completed_at=now()
        where request_id=p_request_id;
    end if;

    balance_credits:=v_account.balance_credits;
    reserved_credits:=v_account.reserved_credits;
    available_credits:=greatest(0,v_account.balance_credits-v_account.reserved_credits);
    return next;
end;
$$;

-- 18) Admin operational views
create or replace view public.hwarang_admin_user_operations_view
with (security_invoker=true)
as
select
    p.*,
    rs.last_seen_at as recent_seen_at,
    rs.status as recent_session_status,
    ra.event_code as recent_activity_code,
    ra.feature_code as recent_feature_code,
    ra.created_at as recent_activity_at,
    coalesce(ca.allocation_credits,0) as training_credit_allocation,
    coalesce(ca.balance_credits,0) as training_credit_balance,
    coalesce(ca.reserved_credits,0) as training_credit_reserved
from public.profiles_admin_view p
left join lateral (
    select s.last_seen_at,s.status
    from public.hwarang_user_sessions s
    where s.user_id=p.user_id
    order by s.last_seen_at desc
    limit 1
) rs on true
left join lateral (
    select a.event_code,a.feature_code,a.created_at
    from public.hwarang_activity_log a
    where a.user_id=p.user_id
    order by a.created_at desc
    limit 1
) ra on true
left join public.hwarang_ai_credit_accounts ca on ca.user_id=p.user_id;

create or replace view public.hwarang_admin_ai_usage_daily_view
with (security_invoker=true)
as
select
    date_trunc('day',created_at) as usage_day,
    user_id,ai_role,model,
    count(*) as request_count,
    sum(input_tokens) as input_tokens,
    sum(cached_tokens) as cached_tokens,
    sum(output_tokens) as output_tokens,
    sum(credits_charged) as credits_charged,
    sum(calculated_cost_usd) as calculated_cost_usd
from public.hwarang_ai_usage_log
group by 1,2,3,4;

