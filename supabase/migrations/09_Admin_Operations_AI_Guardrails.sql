-- 11) User-facing training-credit status
create or replace function public.get_hwarang_training_credit_status(p_user_id uuid)
returns table(
    allocation_credits bigint,
    balance_credits bigint,
    reserved_credits bigint,
    available_credits bigint,
    remaining_percent numeric,
    service_enabled boolean,
    text_enabled boolean,
    voice_enabled boolean,
    assessment_enabled boolean,
    soft_limit_percent integer,
    contact_label text,
    contact_url text
)
language sql
stable
security definer
set search_path=''
as $$
    select
        a.allocation_credits,
        a.balance_credits,
        a.reserved_credits,
        greatest(0::bigint,a.balance_credits-a.reserved_credits),
        case when a.allocation_credits<=0 then 0::numeric
             else round(greatest(
                 0::numeric,
                 (a.balance_credits-a.reserved_credits)::numeric
                 / a.allocation_credits::numeric * 100
             ),1)
        end,
        c.service_enabled,c.text_enabled,c.voice_enabled,c.assessment_enabled,
        c.soft_limit_percent,c.contact_label,c.contact_url
    from public.hwarang_ai_credit_accounts a
    cross join public.hwarang_ai_runtime_config c
    where a.user_id=p_user_id and c.config_id=1;
$$;

