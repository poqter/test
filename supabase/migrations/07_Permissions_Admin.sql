create table if not exists public.hwarang_permissions (
    permission_code text primary key,
    app_code text not null check (app_code in ('workspace','calculator','academy')),
    group_label text not null,
    display_name text not null,
    description text not null default '',
    sort_order integer not null default 0,
    default_granted boolean not null default true,
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.hwarang_user_permissions (
    user_id uuid not null references public.profiles(id) on delete cascade,
    permission_code text not null references public.hwarang_permissions(permission_code) on delete cascade,
    is_allowed boolean not null,
    updated_by uuid references public.profiles(id) on delete set null,
    updated_at timestamptz not null default now(),
    primary key (user_id, permission_code)
);

create index if not exists hwarang_user_permissions_user_idx
on public.hwarang_user_permissions(user_id);

-- 관리 이력
create table if not exists public.hwarang_admin_audit_log (
    id bigint generated by default as identity primary key,
    actor_user_id uuid not null references public.profiles(id) on delete restrict,
    target_user_id uuid references public.profiles(id) on delete set null,
    action text not null,
    details jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now()
);

create index if not exists hwarang_admin_audit_log_created_idx
on public.hwarang_admin_audit_log(created_at desc);

