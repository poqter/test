-- ---------------------------------------------------------
-- 3. 최고관리자는 모든 세부 기능 허용, 일반 사용자는 override 또는 기본값
-- ---------------------------------------------------------
create or replace function public.get_hwarang_effective_permissions(p_user_id uuid)
returns table(permission_code text)
language sql
stable
security definer
set search_path = ''
as $$
    select perm.permission_code
    from public.hwarang_permissions perm
    join public.profiles p on p.id = p_user_id and p.is_active = true
    left join public.hwarang_user_permissions up
      on up.user_id = p_user_id
     and up.permission_code = perm.permission_code
    where perm.is_active = true
      and (
          p.role = 'super_admin'
          or coalesce(up.is_allowed, perm.default_granted) = true
      )
    order by perm.sort_order, perm.permission_code;
$$;

revoke all on function public.get_hwarang_effective_permissions(uuid)
from public, anon, authenticated;
grant execute on function public.get_hwarang_effective_permissions(uuid)
to service_role;

-- ---------------------------------------------------------
-- 4. 최고관리자 전용 일괄 계정/권한 변경 RPC
-- admin은 구조만 유지하며 이 함수 호출 권한을 자동으로 갖지 않습니다.
-- ---------------------------------------------------------
create or replace function public.admin_apply_hwarang_user(
    p_actor_user_id uuid,
    p_target_user_id uuid,
    p_display_name text,
    p_role text,
    p_is_active boolean,
    p_organization_unit_id uuid,
    p_position_code text,
    p_app_access jsonb,
    p_permissions jsonb
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_old_role text;
    v_old_active boolean;
    v_key text;
    v_value text;
begin
    if not exists (
        select 1 from public.profiles
        where id = p_actor_user_id
          and role = 'super_admin'
          and is_active = true
    ) then
        raise exception 'SUPER_ADMIN_REQUIRED';
    end if;

    if p_role not in ('user','admin','super_admin') then
        raise exception 'INVALID_SYSTEM_ROLE';
    end if;

    if p_display_name is null or btrim(p_display_name) = '' or char_length(btrim(p_display_name)) > 60 then
        raise exception 'INVALID_DISPLAY_NAME';
    end if;

    if not exists (select 1 from public.positions where code = p_position_code and is_active = true) then
        raise exception 'INVALID_POSITION';
    end if;

    if p_organization_unit_id is null or not exists (
        select 1 from public.organization_units where id = p_organization_unit_id and is_active = true
    ) then
        raise exception 'INVALID_ORGANIZATION';
    end if;

    select role, is_active into v_old_role, v_old_active
    from public.profiles where id = p_target_user_id for update;
    if not found then
        raise exception 'TARGET_USER_NOT_FOUND';
    end if;

    -- 본인 최고관리자 계정이 잠기는 것을 방지
    if p_target_user_id = p_actor_user_id then
        if p_role <> 'super_admin' or p_is_active = false then
            raise exception 'CANNOT_DEMOTE_OR_DISABLE_SELF';
        end if;
        if coalesce((p_app_access ->> 'workspace')::boolean, false) = false then
            raise exception 'CANNOT_DISABLE_OWN_WORKSPACE';
        end if;
    end if;

    -- 마지막 활성 최고관리자를 제거하지 못하도록 보호
    if v_old_role = 'super_admin' and v_old_active = true
       and (p_role <> 'super_admin' or p_is_active = false)
       and not exists (
           select 1 from public.profiles
           where id <> p_target_user_id
             and role = 'super_admin'
             and is_active = true
       ) then
        raise exception 'LAST_SUPER_ADMIN_REQUIRED';
    end if;

    update public.profiles
    set display_name = btrim(p_display_name),
        role = p_role,
        is_active = p_is_active,
        organization_unit_id = p_organization_unit_id,
        position_code = p_position_code,
        updated_at = now()
    where id = p_target_user_id;

    for v_key, v_value in select key, value from jsonb_each_text(coalesce(p_app_access, '{}'::jsonb)) loop
        if v_key not in ('workspace','calculator','academy') then
            raise exception 'INVALID_APP_CODE';
        end if;
        insert into public.hwarang_app_access(user_id, app_code, is_enabled, updated_at)
        values (p_target_user_id, v_key, v_value::boolean, now())
        on conflict (user_id, app_code) do update
        set is_enabled = excluded.is_enabled,
            updated_at = now();
    end loop;

    for v_key, v_value in select key, value from jsonb_each_text(coalesce(p_permissions, '{}'::jsonb)) loop
        if not exists (
            select 1 from public.hwarang_permissions
            where permission_code = v_key and is_active = true
        ) then
            raise exception 'INVALID_PERMISSION_CODE';
        end if;
        insert into public.hwarang_user_permissions(user_id, permission_code, is_allowed, updated_by, updated_at)
        values (p_target_user_id, v_key, v_value::boolean, p_actor_user_id, now())
        on conflict (user_id, permission_code) do update
        set is_allowed = excluded.is_allowed,
            updated_by = excluded.updated_by,
            updated_at = now();
    end loop;

    insert into public.hwarang_admin_audit_log(actor_user_id, target_user_id, action, details)
    values (
        p_actor_user_id,
        p_target_user_id,
        'account_permissions_updated',
        jsonb_build_object(
            'role', p_role,
            'is_active', p_is_active,
            'organization_unit_id', p_organization_unit_id,
            'position_code', p_position_code,
            'app_access', coalesce(p_app_access, '{}'::jsonb),
            'permissions', coalesce(p_permissions, '{}'::jsonb)
        )
    );
end;
$$;

revoke all on function public.admin_apply_hwarang_user(uuid,uuid,text,text,boolean,uuid,text,jsonb,jsonb)
from public, anon, authenticated;
grant execute on function public.admin_apply_hwarang_user(uuid,uuid,text,text,boolean,uuid,text,jsonb,jsonb)
to service_role;

