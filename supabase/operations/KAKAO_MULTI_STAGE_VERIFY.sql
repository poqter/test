-- Synthetic staging only. Every fixture and mutation rolls back. No network calls.
begin;
create temporary table kakao_test_results(name text);
do $$
declare u uuid; v uuid; sid uuid:=gen_random_uuid(); other_sid uuid:=gen_random_uuid(); t jsonb; snap jsonb; batch jsonb; claim jsonb;
 run1 uuid:=gen_random_uuid(); run2 uuid:=gen_random_uuid(); j1 uuid; j2 uuid; d date:=(clock_timestamp() at time zone 'Asia/Seoul')::date; receipt text:=repeat('c',64); rejected boolean:=false;
begin
 select id into u from public.profiles where login_id='qa_staff';
 select id into v from public.profiles where login_id='qa_peer';
 if u is null or v is null then raise exception 'Synthetic QA fixtures missing'; end if;
 insert into auth.sessions(id,user_id) values(sid,u),(other_sid,v);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',u,'role','authenticated','session_id',sid)::text,true);
 if not private.sales_enabled() then raise exception 'QA user not authorized'; end if;
 t:=public.kakao_service_begin(u,repeat('a',64));
 update public.kakao_multi_oauth set status='exchanging' where id=(t->>'id')::uuid;
 perform public.kakao_service_finish((t->>'id')::uuid,(t->>'generation')::bigint,'900000000001',repeat('encrypted-fixture',4),receipt);
 if (public.kakao_my_status()->>'connection_status')<>'pending_confirmation' then raise exception 'not pending'; end if;
 insert into kakao_test_results values('OAuth remains pending and not enabled');
 perform set_config('request.jwt.claims',jsonb_build_object('sub',v,'role','authenticated','session_id',other_sid)::text,true);
 begin perform public.kakao_confirm_connection(receipt); exception when others then rejected:=true; end;
 if not rejected then raise exception 'Cross-owner receipt accepted'; end if;
 insert into kakao_test_results values('Other workspace account cannot confirm receipt');
 perform set_config('request.jwt.claims',jsonb_build_object('sub',u,'role','authenticated','session_id',sid)::text,true);
 perform public.kakao_confirm_connection(receipt);
 rejected:=false;begin perform public.kakao_confirm_connection(receipt); exception when others then rejected:=true; end;
 if not rejected then raise exception 'Replay accepted'; end if;
 insert into kakao_test_results values('One-time receipt confirmation and replay rejection');
 perform public.kakao_save_preferences(true,to_char(clock_timestamp() at time zone 'Asia/Seoul','HH24:MI'),array[0,1,2,3,4,5,6],true);
 update public.kakao_multi_controls set enabled=true,monthly_message_budget=100,monthly_function_budget=100,cost_verified_until=clock_timestamp()+interval '1 hour';
 if not public.kakao_service_tick_enter(run1) then raise exception 'Run refused'; end if;
 if public.kakao_service_tick_enter(run1) then raise exception 'Repeated run accepted'; end if;
 snap:=private.kakao_service_snapshot(u,d);
 batch:=public.kakao_service_reserve(u,d,(t->>'generation')::bigint,array['첫 번째','두 번째'],private.kakao_service_snapshot_hash(snap));
 if batch->>'status'<>'reserved' then raise exception 'Reservation failed: %',batch; end if;
 if (public.kakao_service_reserve(u,d,(t->>'generation')::bigint,array['duplicate'],private.kakao_service_snapshot_hash(snap))->>'status')<>'already_reserved' then raise exception 'Duplicate day accepted'; end if;
 insert into kakao_test_results values('Daily unique reservation and run budget idempotency');
 select id into j1 from public.kakao_multi_jobs where batch_id=(batch->>'batch_id')::uuid and part=1;
 select id into j2 from public.kakao_multi_jobs where batch_id=(batch->>'batch_id')::uuid and part=2;
 claim:=public.kakao_service_claim(j2,run1);
 if coalesce((claim->>'claimed')::boolean,false) then raise exception 'Part 2 claimed before part1'; end if;
 claim:=public.kakao_service_claim(j1,run1);
 if not coalesce((claim->>'claimed')::boolean,false) then raise exception 'Part1 not claimed: %',claim; end if;
 if not public.kakao_service_validate_claim(j1,(claim->>'claim_token')::uuid) then raise exception 'Claim rejected'; end if;
 if not public.kakao_service_complete(j1,(claim->>'claim_token')::uuid,'accepted') then raise exception 'Acceptance failed'; end if;
 insert into kakao_test_results values('Strict part order and API accepted bookkeeping');
 perform public.kakao_service_tick_enter(run2);
 claim:=public.kakao_service_claim(j2,run2);
 if not coalesce((claim->>'claimed')::boolean,false) then raise exception 'Part2 not claimed'; end if;
 perform public.kakao_disconnect();
 if public.kakao_service_validate_claim(j2,(claim->>'claim_token')::uuid) then raise exception 'Revoked claim still valid'; end if;
 if exists(select 1 from public.kakao_multi_connections where owner_id=u and encrypted_tokens is not null) then raise exception 'Token retained on disconnect'; end if;
 insert into kakao_test_results values('Revocation blocks already claimed next part and erases token');
 if (public.kakao_my_status()::text) like '%encrypted%' or (public.kakao_admin_history(u,7)::text) like '%첫 번째%' then raise exception 'Private data leaked'; end if;
 insert into kakao_test_results values('Status/history exclude token and message body');
end $$;
select jsonb_agg(name) as passed from kakao_test_results;
rollback;
